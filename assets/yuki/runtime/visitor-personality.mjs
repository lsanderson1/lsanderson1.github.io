// Only an anonymous wave flag and greeting indices persist, never chat text.
export class VisitorPersonality {
 constructor(storage,random=Math.random){this.storage=storage;this.random=random;this.seen=false;this.used={en:[],ja:[]};
  try{const s=JSON.parse(storage?.getItem(key));this.seen=s?.seen===true;for(const lang of ['en','ja'])this.used[lang]=Array.isArray(s?.used?.[lang])?[...new Set(s.used[lang].filter(i=>Number.isInteger(i)&&i>=0&&i<greetings[lang].length))].slice(-greetings[lang].length):[];}catch{}
 }
 save(){try{this.storage?.setItem(key,JSON.stringify({seen:this.seen,used:this.used}));}catch{}}
 markMet(){this.seen=true;this.save();}
 next(lang='en'){
  const list=greetings[lang],used=this.used[lang];let candidates=list.map((_,i)=>i).filter(i=>!used.includes(i));
  if(!candidates.length){this.used[lang]=used.slice(-1);candidates=list.map((_,i)=>i).filter(i=>!this.used[lang].includes(i));}
  const index=!this.seen&&!used.length?0:candidates[Math.min(candidates.length-1,Math.floor(this.random()*candidates.length))];this.used[lang].push(index);this.save();return list[index];
 }
 opening(text){return {text,emotion:this.seen?'neutral':'delighted',gesture:this.seen?'talkOpen':'wave',firstMeeting:!this.seen};}
}
// A remembered opening is part of this tab's conversation, not a new reply on
// every bubble click. Any existing exchange (even a failed first send) resumes.
export function conversationOpening(messages,personality,lang='en'){
 return messages.length?null:personality.opening(personality.next(lang));
}
export function replySequence(cue,{firstMeeting=false,talk='talkOpen'}={}){
 if(firstMeeting)return [{...cue,emotion:'delighted',gesture:'wave',firstMeeting:true}];
 // The greeting wave is reserved for the first meeting. Respond emotionally,
 // then use a complete speaking gesture; never blend arms or mouths together.
 const gesture=['talkOpen','talkExplain'].includes(cue.gesture)?cue.gesture:talk;
 if(cue.emotion==='neutral')return [{...cue,gesture}];
 return [{...cue,gesture:'none'},{text:cue.text,emotion:'neutral',gesture}];
}
export function cueArtwork(cue){return cue.gesture==='wave'?'greeting':cue.emotion!=='neutral'?cue.emotion:cue.gesture==='talkOpen'?'talkOpen':'talkExplain';}
