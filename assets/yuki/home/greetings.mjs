const key='yuki-home-greetings-v1';
export function nextHomeGreeting(personality,lang='en'){
 let used=[];try{const v=JSON.parse(personality.storage?.getItem(key));if(Array.isArray(v))used=[...new Set(v.filter(i=>Number.isInteger(i)&&i>=0&&i<homeGreetings.length))];}catch{}
 if(used.length===homeGreetings.length)used=used.slice(-1);
 const candidates=homeGreetings.map((_,i)=>i).filter(i=>!used.includes(i));
 const index=candidates[Math.max(0,Math.min(candidates.length-1,Math.floor(personality.random()*candidates.length)))];
 try{personality.storage?.setItem(key,JSON.stringify([...used,index]));}catch{}
 return {text:homeGreetings[index][lang==='ja'?1:0],greetingId:homeGreetingBase+index};
}
export function localizeHomeGreeting(message,lang){
 const i=message.greetingId-homeGreetingBase,pair=homeGreetings[i];
 return pair&&message.role==='assistant'&&pair.includes(message.text)?{...message,text:pair[lang==='ja'?1:0]}:message;
}
